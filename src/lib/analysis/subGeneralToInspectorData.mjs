export function isSubGeneralLevel(level) {
  const s = String(level || '');
  return SUB_GENERAL_LEVELS.some((l) => l.source_level === s) || /ผกก\.|สว\.|สับเปลี่ยนหมุนเวียน/.test(s);
}

export function resolveJobTier(jobData = {}) {
  const explicit = String(jobData.analysis_tier || '');
  if (explicit === 'general') return 'general';
  if (explicit === 'sub_general_to_inspector' || explicit === 'sub_general') return 'sub_general_to_inspector';
  const level = String(jobData.level || '');
  if (isSubGeneralLevel(level)) return 'sub_general_to_inspector';
  if (DEFAULT_GENERAL_ACCOUNTS.some((a) => a.source_level === level)) return 'general';
  const motion = String(jobData.appointment_motion || '');
  const unitType = String(jobData.unit_type || '');
  const annexStatus = String(jobData.annex_status || '');
  const combinedText = [jobData.title, jobData.rank_position, jobData.claim, jobData.response, jobData.issues]
    .filter(Boolean)
    .join(' ');
  if (
    Boolean(annexStatus) ||
    unitType === 'non_opb_bch' ||
    unitType === 'opb_unit' ||
    unitType === 'direct_tr_unit' ||
    ['investigator_adjustable', 'station_chief_transfer', 'first_time_station_chief', 'urgent_policy_defect'].includes(motion) ||
    /รอง\s*ผบก\.?\s*ลงมาถึง\s*สว|ผกก\.|รอง\s*ผกก\.|สารวัตร|สว\.|รอง\s*สว\.|ว\s*2456|ว\s*๒๔๕๖/.test(combinedText)
  ) {
    return 'sub_general_to_inspector';
  }
  return 'general';
}

export function resolveSeniorityQuotaSpec(jobData = {}) {
  const tier = resolveJobTier(jobData);
  const level = String(jobData.level || '');
  if (tier === 'sub_general_to_inspector') {
    return {
      tier: 'sub_general_to_inspector',
      ratio: 0.33,
      pctLabel: '33%',
      formula: 'CEILING(actual_vacancies × 0.33) ตาม พ.ร.บ.ตำรวจแห่งชาติฯ ม.๘๒(๓) และ กฎ ก.ตร.ฯ ข้อ ๔๗(๓) (ไม่น้อยกว่าร้อยละ ๓๓ ของจำนวนตำแหน่งว่างในแต่ละระดับของหน่วย)',
    };
  }
  if (/ผู้ช่วย\s*ผบ\.ตร\.|ผบช\.\s*\/\s*จตร\./.test(level) || jobData.appointment_motion === 'general_seniority_100') {
    return {
      tier: 'general',
      ratio: 1.0,
      pctLabel: '100%',
      formula: '100% เรียงตามลำดับอาวุโส ตาม พ.ร.บ.ตำรวจแห่งชาติฯ ม.๘๒(๑) และ กฎ ก.ตร.ฯ ข้อ ๔๗(๑)',
    };
  }
  return {
    tier: 'general',
    ratio: 0.5,
    pctLabel: '50%',
    formula: 'CEILING(actual_vacancies × 0.50)',
  };
}

